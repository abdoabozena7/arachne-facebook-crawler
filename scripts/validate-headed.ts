import { mkdir, writeFile, readFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createApp } from '../src/server.js';

const out = path.resolve('output/playwright'); await mkdir(out, { recursive: true });
const app = await createApp({ port: 0, openDashboard: true, defaults: { maxPosts: 4, animationSpeed: 3, operationDelayMs: 180, screenshots: true } });
const errors: string[] = [];
try {
  const page = app.dashboardPage!;
  page.on('pageerror', error => errors.push(error.message));
  assert.ok(app.windowLayout, 'The app positions its own windows');
  assert.equal(app.windowLayout.source.left, app.windowLayout.panel.left + app.windowLayout.panel.width);
  assert.equal(app.windowLayout.source.top, app.windowLayout.panel.top);
  assert.equal(await page.getByRole('button').count(), 1);
  assert.equal(await page.locator('textarea').count(), 1);
  const health = await (await page.request.get(app.url + '/api/health')).json();
  assert.equal(health.application, 'arachne'); assert.equal(health.pid, process.pid);
  assert.equal((await page.request.post(app.url + '/api/open-panel', { data: {} })).status(), 200);
  assert.equal(app.dashboardPage, page, 'Repeated launch reuses the existing panel');
  assert.equal(await page.locator('body').evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
  assert.equal(await page.locator('html').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 255, 255)');
  assert.equal(await page.locator('html').evaluate(el => getComputedStyle(el).color), 'rgb(17, 17, 17)');
  await page.screenshot({ path: path.join(out, 'simple-idle.png'), fullPage: true });

  await page.goto(app.url + '/?fixture=comments');
  await page.getByText('Test fixture · not Facebook data', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Start', exact: true }).click();
  await page.getByRole('button', { name: 'Stop', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelectorAll('.record').length >= 1);
  assert.ok(await page.locator('.record').first().evaluate(el => el.getAnimations().length > 0), 'A real saved record animates into the collection');
  await app.crawler.pause();
  await page.getByText('Collection is paused.', { exact: true }).waitFor();
  assert.equal(await page.locator('#source-url').isEnabled(), false);
  await page.screenshot({ path: path.join(out, 'simple-live.png'), fullPage: true });
  assert.equal((await page.request.post(app.url + '/api/open-panel', { data: { refresh: true } })).status(), 200);
  await page.getByText('Collection is paused.', { exact: true }).waitFor();
  const pausedOrder = app.crawler.snapshot().records.map(record => record.record_id).reverse();
  assert.deepEqual(await page.locator('.record').evaluateAll(rows => rows.map(row => (row as HTMLElement).dataset.recordId)), pausedOrder, 'An active crawl survives reopening its panel');
  assert.equal(await page.locator('.record').evaluateAll(rows => rows.reduce((sum, row) => sum + row.getAnimations().length, 0)), 0, 'Reconnects do not replay collection effects');
  await app.crawler.resume(); await app.crawler.wait();
  await page.getByText('4 comments collected · collection limit reached.', { exact: true }).waitFor();
  const result = app.crawler.snapshot();
  assert.equal(result.counters.saved, 4); assert.equal(result.counters.duplicates, 1);
  assert.equal(await page.getByRole('button').count(), 1);
  assert.equal(await page.locator('.record').count(), 4);
  const expectedOrder = result.records.map(record => record.record_id).reverse();
  assert.deepEqual(await page.locator('.record').evaluateAll(rows => rows.map(row => (row as HTMLElement).dataset.recordId)), expectedOrder, 'Newest saved comment stays at the top');
  assert.ok(result.records.every(record => record.record_type === 'comment' && record.source_mode === 'fixture'));
  const manifest = JSON.parse(await readFile(path.join(app.crawler.outputDirectory!, 'manifest.json'), 'utf8'));
  assert.equal(manifest.source_window.left, app.windowLayout.source.left);
  assert.equal(manifest.source_window.top, app.windowLayout.source.top);
  assert.ok(manifest.source_window.width >= 500);
  assert.match(await page.locator('.record-meta a').first().getAttribute('href') ?? '', /comment_id=/);
  const downloaded = page.waitForEvent('download'); await page.getByRole('link', { name: 'Save JSON', exact: true }).click();
  await (await downloaded).saveAs(path.join(out, 'simple-export.json'));
  assert.equal(JSON.parse(await readFile(path.join(out, 'simple-export.json'), 'utf8')).length, 4);
  assert.equal(JSON.parse(await readFile(path.join(out, 'simple-export.json'), 'utf8'))[0].record_id, result.records[0].record_id, 'Presentation order does not change stored provenance order');
  await page.screenshot({ path: path.join(out, 'simple-completed.png'), fullPage: true });

  assert.equal((await page.request.post(app.url + '/api/open-panel', { data: { refresh: true } })).status(), 200);
  await page.getByText('Ready.', { exact: true }).waitFor();
  assert.equal(await page.locator('.record').count(), 0, 'Reopening after a completed crawl starts with an empty collection');
  assert.equal(await page.locator('#record-count').textContent(), '0');
  assert.equal(await page.getByRole('link', { name: 'Save JSON', exact: true }).isVisible(), false);
  assert.equal((await (await page.request.get(app.url + `/api/runs/${result.run_id}/data.json`)).json()).length, 4, 'An empty panel does not delete saved records');
  await page.screenshot({ path: path.join(out, 'simple-fresh-empty.png'), fullPage: true });

  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('button', { name: 'Start', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.record').length >= 1);
  assert.equal(await page.locator('.record').evaluateAll(rows => rows.reduce((sum, row) => sum + row.getAnimations().length, 0)), 0, 'Reduced motion disables live collection effects');
  await page.getByRole('button', { name: 'Stop', exact: true }).click();
  await app.crawler.wait();
  assert.equal(app.crawler.snapshot().state, 'stopped');
  await page.getByRole('button', { name: 'Start', exact: true }).waitFor();
  await page.route('**/api/config', async route => { await new Promise(resolve => setTimeout(resolve, 350)); await route.continue(); });
  await page.goto(app.url);
  await page.getByLabel('Post link', { exact: true }).fill('https://example.com/');
  await page.getByRole('button', { name: 'Start', exact: true }).click();
  await page.getByText('Use an HTTPS facebook.com page URL without credentials or a custom port', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Start', exact: true }).isEnabled(), true);
  await page.waitForTimeout(450);
  assert.equal(await page.getByLabel('Post link', { exact: true }).inputValue(), 'https://example.com/');

  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(out, 'simple-mobile.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.equal(errors.length, 0, errors.join('\n'));
  await writeFile(path.join(out, 'simple-validation.json'), JSON.stringify({ validated_at: new Date().toISOString(), mode: 'fixture', headed: true, run_id: result.run_id, counters: result.counters, window_layout: app.windowLayout, actual_source_window: manifest.source_window, browser_errors: errors, checks: ['one button and one link input', 'white surface and black text', 'side-by-side headed windows', 'real comment arrivals', 'newest-first collection', 'animated arrival', 'active reconnect without replay', 'fresh empty panel with preserved exports', 'reduced motion', 'Start/Stop', 'pause/resume API', 'source links', 'JSON download', 'visible validation errors', 'mobile overflow'], live_facebook: 'fixture_validation_only' }, null, 2));
  console.log(`Simple headed UI validation passed. Evidence: ${result.run_id}\nScreenshots: ${out}`);
} finally { await app.close(); }
